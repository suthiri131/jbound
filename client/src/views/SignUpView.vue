<script setup>
import { computed, reactive, ref } from 'vue';
import { RouterLink, useRoute, useRouter } from 'vue-router';
import AuthShell from '@/components/auth/AuthShell.vue';
import { errorMessage } from '@/lib/api';
import { useAuthStore } from '@/stores/auth';
import { safeRedirect } from '@/utils/safeRedirect';

const auth = useAuthStore();
const route = useRoute();
const router = useRouter();

const next = computed(() => safeRedirect(route.query.next));
const signInLink = computed(() => ({ name: 'sign-in', query: route.query.next ? { next: route.query.next } : {} }));

const form = reactive({ firstName: '', lastName: '', email: '', password: '', confirmPassword: '' });
const showPassword = ref(false);
const saving = ref(false);
const error = ref('');

// Shown live once they start typing in the confirm box. Usernames are generated by the server now.
const passwordsMismatch = computed(() => form.confirmPassword !== '' && form.password !== form.confirmPassword);

async function submit() {
  if (saving.value) return;
  error.value = '';
  if (form.password.length < 8) {
    error.value = 'Use at least 8 characters for your password.';
    return;
  }
  if (passwordsMismatch.value) return; // the hint under "Confirm password" already explains why
  saving.value = true;
  try {
    await auth.signup({ firstName: form.firstName.trim(), lastName: form.lastName.trim(), email: form.email.trim(), password: form.password });
    await router.replace(next.value);
  } catch (e) {
    // the API's validation errors carry a readable first issue in `details`
    error.value = e?.response?.data?.details?.[0]?.message || errorMessage(e, 'Could not create your account.');
  } finally {
    saving.value = false;
  }
}
</script>

<template>
  <AuthShell eyebrow="Join the crew" title="Create your account" subtitle="Free, and it takes under a minute.">
    <form class="card card-pad stack" novalidate @submit.prevent="submit">
      <div class="name-row">
        <label class="field">
          First name
          <input v-model="form.firstName" class="input" type="text" autocomplete="given-name" required maxlength="30" placeholder="e.g. Benjamin" />
        </label>
        <label class="field">
          Last name
          <input v-model="form.lastName" class="input" type="text" autocomplete="family-name" required maxlength="30" placeholder="e.g. Netanyahu" />
        </label>
      </div>
      <label class="field">
        Email
        <input v-model="form.email" class="input" type="email" autocomplete="email" required placeholder="yahu@example.com" />
      </label>
      <label class="field">
        Password
        <span class="pw">
          <input v-model="form.password" class="input" :type="showPassword ? 'text' : 'password'" autocomplete="new-password" required minlength="8" placeholder="At least 8 characters" />
          <button type="button" class="btn btn-sm btn-ghost" :aria-pressed="showPassword" @click="showPassword = !showPassword">{{ showPassword ? 'Hide' : 'Show' }}</button>
        </span>
      </label>
      <label class="field">
        Confirm password
        <input v-model="form.confirmPassword" class="input" :type="showPassword ? 'text' : 'password'" autocomplete="new-password" required :aria-invalid="passwordsMismatch" placeholder="Confirm password" />
        <span v-if="passwordsMismatch" class="error-text" role="alert">Passwords do not match.</span>
      </label>

      <p v-if="error" class="error-text" role="alert">{{ error }}</p>

      <button class="btn btn-primary" type="submit" :disabled="saving || !form.firstName.trim() || !form.lastName.trim() || !form.email || !form.password || !form.confirmPassword">
        {{ saving ? 'Creating account…' : 'Create account' }}
      </button>
      <p class="muted alt">Already have an account? <RouterLink :to="signInLink">Sign in</RouterLink></p>
    </form>
  </AuthShell>
</template>

